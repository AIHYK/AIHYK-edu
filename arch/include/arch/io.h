/* ================================================================
 * arch/io.h — I/O 端口访问的架构抽象接口
 *
 * x86 通过 in/out 指令访问 I/O 端口（独立地址空间，与内存分离）。
 * 其他架构（ARM/RISC-V）使用 MMIO（内存映射 I/O），
 * 实现方式不同，但接口可以统一。
 *
 * 这个头文件提供：
 *   outb(port, val) — 向端口写一个字节
 *   inb(port)      — 从端口读一个字节
 *   outw/inw/outl/inl — 16/32 位版本
 *   io_wait()      — I/O 后短暂延时（旧硬件需要）
 *
 * 后续课程（中断、PCI、磁盘驱动）会大量使用这些函数。
 * ================================================================ */

#ifndef ARCH_IO_H
#define ARCH_IO_H

#include <kernel/types.h>

/* ---------------------------------------------------------------
 * outb — 向 I/O 端口写一个字节
 *
 * 参数：
 *   port - I/O 端口号（0 ~ 65535）
 *   val  - 要写入的字节
 *
 * 内联汇编说明：
 *   "outb %0, %1"
 *     %0 = val（用 al 寄存器，即一个字节）
 *     %1 = port（用 dx 寄存器）
 *   outb al, dx  →  把 al 的值写到 dx 指定的端口
 *
 * "a"(val) 约束：把 val 放到 al（8 位）
 * "d"(port) 约束：把 port 放到 dx（16 位）
 * --------------------------------------------------------------- */
static inline void outb(u16 port, u8 val) {
    __asm__ volatile ("outb %0, %1" : : "a"(val), "d"(port));
}

/* ---------------------------------------------------------------
 * inb — 从 I/O 端口读一个字节
 *
 * 返回值：读到的字节
 *
 * 内联汇编说明：
 *   "inb %1, %0"
 *     %1 = port（用 dx）
 *     %0 = 输出（用 al）
 *   inb al, dx  →  从 dx 指定的端口读一个字节到 al
 *
 * "=a"(ret) 输出约束：把 al 的值输出到 ret
 * "d"(port) 输入约束：把 port 放到 dx
 * --------------------------------------------------------------- */
static inline u8 inb(u16 port) {
    u8 ret;
    __asm__ volatile ("inb %1, %0" : "=a"(ret) : "d"(port));
    return ret;
}

/* ---------------------------------------------------------------
 * outw / inw — 16 位 I/O
 * 用 ax 寄存器（16 位）
 * --------------------------------------------------------------- */
static inline void outw(u16 port, u16 val) {
    __asm__ volatile ("outw %0, %1" : : "a"(val), "d"(port));
}

static inline u16 inw(u16 port) {
    u16 ret;
    __asm__ volatile ("inw %1, %0" : "=a"(ret) : "d"(port));
    return ret;
}

/* ---------------------------------------------------------------
 * outl / inl — 32 位 I/O
 * 用 eax 寄存器（32 位）
 * --------------------------------------------------------------- */
static inline void outl(u16 port, u32 val) {
    __asm__ volatile ("outl %0, %1" : : "a"(val), "d"(port));
}

static inline u32 inl(u16 port) {
    u32 ret;
    __asm__ volatile ("inl %1, %0" : "=a"(ret) : "d"(port));
    return ret;
}

/* ---------------------------------------------------------------
 * io_wait — I/O 操作后短暂延时
 *
 * 为什么要延时？
 *   旧硬件（如 ISA 总线设备）处理 I/O 较慢，
 *   连续两次 outb 之间可能来不及响应，需要"喘口气"。
 *   现代硬件一般不需要，但加上无害。
 *
 * 实现技巧：向端口 0x80 写一个字节
 *   端口 0x80 是"诊断端口"，写任何值都不会有副作用，
 *   但这次写操作本身会消耗约 1 微秒，正好用来延时。
 * --------------------------------------------------------------- */
static inline void io_wait(void) {
    __asm__ volatile ("outb %0, %1" : : "a"((u8)0), "d"((u16)0x80));
}

#endif /* ARCH_IO_H */
