/* ================================================================
 * arch/console.h — 早期控制台输出的架构抽象接口
 *
 * 内核刚启动时，还没有驱动、没有文件系统、没有终端。
 * 但我们需要输出调试信息。
 *
 * "早期控制台"就是内核启动阶段最原始的输出方式：
 *   x86-64:  VGA 文本模式（往 0xB8000 写字符）
 *   RISC-V:  UART 串口（往 MMIO 地址写字符）
 *   模拟器:  printf（直接输出到宿主终端）
 *
 * 这个抽象让 kernel/main.c 可以 print 信息，
 * 而不知道底层是 VGA、UART 还是 printf。
 * ================================================================ */

#ifndef ARCH_CONSOLE_H
#define ARCH_CONSOLE_H

/* ---------------------------------------------------------------
 * arch_console_init — 初始化早期控制台
 *
 * x86-64 实现：VGA 文本模式清屏
 * RISC-V 实现：初始化 UART
 * 模拟器实现：无操作
 * --------------------------------------------------------------- */
void arch_console_init(void);

/* ---------------------------------------------------------------
 * arch_console_putchar — 输出一个字符
 *
 * 参数：c - 要输出的字符（ASCII）
 * 支持 '\n'（换行）和 '\r'（回车）
 * --------------------------------------------------------------- */
void arch_console_putchar(char c);

/* ---------------------------------------------------------------
 * arch_console_print — 输出字符串
 *
 * 参数：s - 以 '\0' 结尾的字符串
 * 逐字符调用 arch_console_putchar
 * --------------------------------------------------------------- */
void arch_console_print(const char *s);

/* ---------------------------------------------------------------
 * 颜色定义
 *
 * VGA: 16 色（4位前景 + 4位背景）
 * UART: 无颜色（只有文字）
 * printf: 无颜色
 * --------------------------------------------------------------- */
#define CON_COLOR_DEFAULT   0    /* 默认色 */
#define CON_COLOR_WHITE     1    /* 白色（高亮） */
#define CON_COLOR_GREEN     2    /* 绿色 */
#define CON_COLOR_RED       3    /* 红色 */
#define CON_COLOR_YELLOW    4    /* 黄色 */
#define CON_COLOR_CYAN      5    /* 青色 */

/* ---------------------------------------------------------------
 * arch_console_set_color — 设置后续输出的颜色
 * --------------------------------------------------------------- */
void arch_console_set_color(int color);

#endif /* ARCH_CONSOLE_H */
