/* ================================================================
 * arch/cpu.h — CPU 操作的架构抽象接口
 *
 * "架构抽象"的意思：
 *   这个头文件只声明"做什么"，不说"怎么做"。
 *   "怎么做"在 arch/x86_64/cpu.c 里实现。
 *   换到 RISC-V 时，只需要加 arch/riscv64/cpu.c，
 *   不改这个头文件，不改 kernel/ 下的任何代码。
 *
 * 【Lesson 3 新增】
 *   增加了中断使能的 save/restore 接口：
 *     arch_irq_save()  - 保存当前 IF 状态 + 关中断
 *     arch_irq_restore() - 恢复保存的 IF 状态
 *
 *   这两个用于临界区保护：
 *     u64 flags = arch_irq_save();   // 关中断
 *     修改共享数据结构...
 *     arch_irq_restore(flags);       // 恢复
 *
 *   比单纯 arch_cli()/arch_sti() 更安全：
 *     - 如果调用前中断已关（flags.IF=0），restore 后仍关
 *     - 不会"误开中断"
 * ================================================================ */

#ifndef ARCH_CPU_H
#define ARCH_CPU_H

#include <kernel/types.h>

/* ---------------------------------------------------------------
 * arch_halt — 永久停机
 *
 * 语义：CPU 停止执行，进入低功耗状态，不可唤醒。
 *
 * 什么时候用：
 *   - 内核 panic 后，系统已损坏，安全停机
 *   - 找到无法恢复的错误，主动停下
 *
 * 为什么需要抽象：
 *   x86-64:   cli + hlt（关中断 + 停机指令）
 *   RISC-V:   死循环 + wfi
 *   模拟器:   exit(0)
 * --------------------------------------------------------------- */
void arch_halt(void);

/* ---------------------------------------------------------------
 * arch_cli — 关闭中断 (Clear Interrupt Enable)
 *
 * 语义：CPU 不响应外部中断（键盘、时钟、网卡...）
 *       中断信号在控制器里排队，等 arch_sti 后再处理。
 *
 * 什么时候用：
 *   - 修改内核数据结构时，防止被中断打断
 *     如果改链表到一半被中断，中断处理程序也访问
 *     同一个链表 → 数据结构损坏 → 崩溃
 * --------------------------------------------------------------- */
void arch_cli(void);

/* ---------------------------------------------------------------
 * arch_sti — 开启中断 (Set Interrupt Enable)
 *
 * 语义：CPU 开始响应外部中断。
 *       调用后，排队的中断会立即触发。
 * --------------------------------------------------------------- */
void arch_sti(void);

/* ---------------------------------------------------------------
 * arch_irq_save — 保存当前 IF 状态并关中断
 *
 * 返回值：保存的 RFLAGS（包含原 IF 位）
 *
 * 实现原理（x86-64）：
 *   1. pushfq     - 把 RFLAGS 压栈
 *   2. pop rax    - 取出 RFLAGS 到 RAX
 *   3. cli        - 关中断
 *   4. 返回 RAX
 *
 * 用法：
 *   u64 flags = arch_irq_save();
 *   ... 临界区代码（中断关闭）...
 *   arch_irq_restore(flags);
 *
 * 为什么不直接 cli + sti：
 *   如果调用前 IF=0（中断已关），结束时 sti 会误开中断！
 *   save/restore 保留原状态，正确处理"嵌套临界区"。
 * --------------------------------------------------------------- */
u64 arch_irq_save(void);

/* ---------------------------------------------------------------
 * arch_irq_restore — 恢复保存的 RFLAGS（包含 IF 状态）
 *
 * 参数：flags - arch_irq_save() 返回的值
 *
 * 实现原理（x86-64）：
 *   1. push flags - 把保存的值压栈
 *   2. popfq      - 弹到 RFLAGS（恢复原 IF 位）
 *
 * 如果原 IF=0，恢复后仍关；如果原 IF=1，恢复后开。
 * --------------------------------------------------------------- */
void arch_irq_restore(u64 flags);

/* ---------------------------------------------------------------
 * arch_get_cpu_id — 获取当前 CPU 编号
 *
 * 返回值：当前 CPU 的编号（0, 1, 2, ...）
 *         单核系统始终返回 0
 *
 * 什么时候用：
 *   - 多核系统中，per-CPU 数据用这个索引访问
 *   - 调试时打印"哪个 CPU 在执行"
 * --------------------------------------------------------------- */
int arch_get_cpu_id(void);

#endif /* ARCH_CPU_H */
