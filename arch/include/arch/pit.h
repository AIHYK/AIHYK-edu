/* ================================================================
 * arch/pit.h — 8254 PIT（可编程间隔定时器）架构抽象接口
 *
 * 【Lesson 3 核心新增】
 *
 * 8254 PIT 是什么：
 *   PC 上有一个 8254 定时器芯片，输入时钟频率固定 1.193182 MHz
 *   （= 14.31818 MHz / 12，源于 NTSC 彩色副载波，历史包袱）。
 *
 *   8254 有 3 个独立通道：
 *     通道 0：连到 8259 PIC 的 IRQ0，可触发定时中断
 *     通道 1：DRAM 刷新（PC/AT 上已废弃，PC 时代用过）
 *     通道 2：连到 PC 扬声器，生成方波（"哔"声）
 *
 *   每个通道有 16 位计数器，每来一个时钟脉冲就 -1，
 *   减到 0 时输出信号（边沿），并重新装载初值。
 *
 *   输出频率 = 输入频率 / 计数值
 *     计数 = 1   → 1.193182 MHz（最快）
 *     计数 = 0   → 65536（16 位减到 0，下一轮再 65536）
 *     计数 = 11932 → 100 Hz（每 10ms 一次）
 *     计数 = 0xFFFF = 65535 → 18.2 Hz（每 55ms 一次，BIOS 默认）
 *
 * 8254 端口：
 *   0x40 - 通道 0 数据端口
 *   0x41 - 通道 1 数据端口
 *   0x42 - 通道 2 数据端口
 *   0x43 - 控制字寄存器
 *
 * 控制字格式（写到 0x43）：
 *   bit 7-6  通道选择（00=ch0, 01=ch1, 10=ch2, 11=read-back）
 *   bit 5-4  访问模式（00=latch, 01=low byte, 10=high byte, 11=both）
 *   bit 3-1  工作模式（000=interrupt on terminal count, ...
 *                       011=square wave generator）
 *   bit 0    计数制（0=binary, 1=BCD）
 *
 *   我们的配置：
 *     0x36 = 00 11 011 0
 *            ch0 | both | mode3(square wave) | binary
 *
 *   为什么用 mode3（方波）而不是 mode2？
 *     mode2 输出的是窄脉冲，mode3 输出的是 50% 占空比方波，
 *     都能触发 IRQ0，但 mode3 对旧硬件更友好。
 *     Linux 也用 mode3。
 *
 * 【时钟频率相关】
 *   基础频率：1,193,182 Hz
 *   分频器：1~65536（写 0 等于 65536）
 *   实际中断频率 = 1193182 / divisor
 *
 *   常见配置：
 *     divisor = 11932 → 100 Hz（每 10ms 一次）← 我们用这个
 *     divisor = 11932 → 100 ticks/sec
 *     每 tick = 10ms
 * ================================================================ */

#ifndef ARCH_PIT_H
#define ARCH_PIT_H

#include <kernel/types.h>

/* PIT 输入时钟频率（Hz） */
#define PIT_BASE_FREQUENCY 1193182

/* 默认中断频率（每秒中断次数）
 * 100Hz = 每 10ms 一次中断，足够做调度器时基 */
#define PIT_DEFAULT_FREQUENCY 100

/* ---------------------------------------------------------------
 * arch_pit_init — 初始化 8254 PIT 通道 0
 *
 * 参数：frequency - 期望的中断频率（Hz），1~65535
 *
 * 流程：
 *   1. 计算 divisor = PIT_BASE_FREQUENCY / frequency
 *   2. 写控制字到 0x43（通道 0，两字节访问，mode 3，二进制）
 *   3. 写 divisor 低字节到 0x40
 *   4. 写 divisor 高字节到 0x40
 *
 * 之后 PIT 通道 0 每秒触发 `frequency` 次 IRQ0，
 * IRQ0 在 PIC 里被重映射到向量 32，进入我们的中断处理。
 * --------------------------------------------------------------- */
void arch_pit_init(u32 frequency);

/* ---------------------------------------------------------------
 * arch_pit_get_tick_count — 获取自启动以来的 tick 数
 *
 * 每次 IRQ0 中断，tick 数 +1。
 * 100Hz 下每 tick = 10ms。
 * 可用于：
 *   - 简单延时（忙等）
 *   - 时间戳
 *   - 后续课程的调度器时基
 * --------------------------------------------------------------- */
u64 arch_pit_get_tick_count(void);

/* ---------------------------------------------------------------
 * arch_pit_increment_tick — 增加 tick 计数
 *
 * 由 IRQ0 中断处理程序调用（在 irq.c 里）。
 * 提供独立接口封装 tick 变量（外部不能直接访问 static 变量）。
 * --------------------------------------------------------------- */
void arch_pit_increment_tick(void);

#endif /* ARCH_PIT_H */
