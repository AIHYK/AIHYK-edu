/* ================================================================
 * arch/boot.h — 启动信息的架构抽象接口
 *
 * 内核启动时，需要从 bootloader 获取硬件信息：
 *   - 有多少内存？分布在哪些地址？
 *   - 有哪些硬件设备？
 *   - 启动参数是什么？
 *
 * 不同 bootloader 提供信息的方式完全不同：
 *   x86 + GRUB:       multiboot_info 结构（EBX 寄存器指向）
 *   RISC-V + OpenSBI: 设备树 (DTB)
 *   ARM64 + UEFI:     UEFI 内存映射
 *
 * 我们抽象成统一格式，kernel/ 下的代码只看统一格式。
 * ================================================================ */

#ifndef ARCH_BOOT_H
#define ARCH_BOOT_H

#include <kernel/types.h>

/* ---------------------------------------------------------------
 * 内存区域类型
 *
 * BIOS/UEFI 会告诉内核：这段内存是什么用途
 * 内核只能分配 MEM_USABLE 类型的内存
 * --------------------------------------------------------------- */
enum mem_type {
    MEM_USABLE,        /* 可用内存，内核可以自由分配 */
    MEM_RESERVED,      /* 保留区域，被 BIOS/硬件占用，不能碰 */
    MEM_KERNEL,        /* 内核自身占用的区域（代码+数据+BSS） */
    MEM_MMIO,          /* 设备 MMIO 区域（VGA、PCI 配置空间等） */
    MEM_ACPI,          /* ACPI 表所在区域 */
};

/* ---------------------------------------------------------------
 * 内存区域描述
 *
 * bootloader 报告的每一段内存区域用这个结构描述
 * --------------------------------------------------------------- */
struct mem_region {
    paddr_t      base;     /* 起始物理地址 */
    usize_t      length;   /* 长度（字节） */
    enum mem_type type;    /* 类型 */
};

/* ---------------------------------------------------------------
 * 启动信息 — 架构无关的统一格式
 *
 * arch_boot_init() 会把 bootloader 的原始信息
 * 转换成这个格式，之后内核核心代码只看这个
 * --------------------------------------------------------------- */
struct boot_info {
    struct mem_region *regions;      /* 内存区域数组 */
    int               region_count;  /* 区域数量 */
    const char       *cmdline;       /* 启动命令行参数 */
};

/* ---------------------------------------------------------------
 * arch_boot_init — 解析启动信息
 *
 * 参数：
 *   info - 输出：填充 boot_info 结构
 *
 * kernel/main.c 调用 arch_boot_init(&info)
 * 之后只用 info，不知道也不关心信息来自 GRUB 还是 DTB
 * --------------------------------------------------------------- */
void arch_boot_init(struct boot_info *info);

#endif /* ARCH_BOOT_H */
