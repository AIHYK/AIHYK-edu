/* ================================================================
 * arch/x86_64/cpu.c — x86-64 的 CPU 操作实现
 *
 * 实现 arch/cpu.h 定义的接口。
 *
 * x86 特有知识：
 *   RFLAGS 寄存器：CPU 的状态标志
 *     bit 9 = IF (Interrupt Flag)：1=中断开启, 0=中断关闭
 *   cli 指令：清除 IF 位（关中断）
 *   sti 指令：设置 IF 位（开中断）
 *   hlt 指令：CPU 停机，等中断唤醒
 *   pushfq 指令：把 RFLAGS 压栈（64 位）
 *   popfq  指令：从栈弹到 RFLAGS
 *
 * 【Lesson 3 新增】
 *   - arch_irq_save(): 保存 RFLAGS + 关中断
 *   - arch_irq_restore(): 恢复保存的 RFLAGS
 *
 *   这两个用于临界区保护，比 cli/sti 更安全。
 * ================================================================ */

#include <arch/cpu.h>

/* ---------------------------------------------------------------
 * arch_halt — 永久停机
 *
 * x86_64 实现：
 *   1. cli — 关中断（不让任何中断唤醒 CPU）
 *   2. hlt — CPU 停机
 *   3. 死循环兜底（万一 NMI 等不可屏蔽中断唤醒了 CPU）
 *
 * __asm__ volatile 的含义：
 *   __asm__   — 内联汇编（在 C 代码里写汇编指令）
 *   volatile  — 告诉编译器"别优化这段代码"
 *              如果没有 volatile，编译器可能：
 *              - 认为 hlt 是死代码，直接删除
 *              - 把 cli+hl+jmp 重排
 * ::: 的含义（内联汇编的三个冒号）：
 *   第一个冒号后 = 输出操作数（无）
 *   第二个冒号后 = 输入操作数（无）
 *   第三个冒号后 = clobber 列表（无）
 * --------------------------------------------------------------- */
void arch_halt(void) {
    __asm__ volatile (
        "cli\n\t"      /* 关中断：清除 RFLAGS.IF */
        "hlt\n\t"      /* 停机：CPU 进入低功耗状态 */
        :::            /* 无输出、无输入、无 clobber */
    );

    /* 兜底死循环：如果 hlt 被不可屏蔽中断唤醒 */
    while (1) {}
}

/* ---------------------------------------------------------------
 * arch_cli — 关中断
 *
 * x86_64 实现：执行 cli 指令
 *
 * "memory" clobber 的含义：
 *   告诉编译器"这条指令可能修改内存"
 *   防止编译器把 cli 前后的内存操作重排到 cli 的另一侧
 *
 *   例子：
 *     data->ready = 1;   // ① 标记数据准备好
 *     arch_cli();         // ② 关中断
 *     process(data);      // ③ 处理数据
 *
 *   没有 "memory" clobber，编译器可能重排为 ②①③
 *   但如果中断处理程序读 data->ready，顺序就很重要了
 *   "memory" 确保编译器不重排
 * --------------------------------------------------------------- */
void arch_cli(void) {
    __asm__ volatile ("cli" ::: "memory");
}

/* ---------------------------------------------------------------
 * arch_sti — 开中断
 * --------------------------------------------------------------- */
void arch_sti(void) {
    __asm__ volatile ("sti" ::: "memory");
}

/* ---------------------------------------------------------------
 * arch_irq_save — 保存当前 RFLAGS 并关中断
 *
 * 实现原理：
 *   1. pushfq  - 把 RFLAGS 压入栈顶
 *   2. pop %0  - 弹出栈顶到输出变量（编译器分配寄存器）
 *   3. cli     - 关中断
 *
 * 输出约束 "=r"(flags)：
 *   = 表示输出（write-only）
 *   r 表示由编译器选任意通用寄存器
 *
 * "memory" clobber：
 *   防止编译器重排内存操作越过这里
 *
 * 返回值：保存的 RFLAGS（含原 IF 位）
 *
 * 用例（保护链表）：
 *   u64 s = arch_irq_save();     // 关中断，记下原状态
 *   list_remove(node);           // 临界区
 *   arch_irq_restore(s);         // 恢复（原 IF=1 才开中断）
 * --------------------------------------------------------------- */
u64 arch_irq_save(void) {
    u64 flags;
    __asm__ volatile (
        "pushfq\n\t"     /* RFLAGS 压栈 */
        "popq %0\n\t"    /* 弹到 %0 (= flags) */
        "cli\n\t"        /* 关中断 */
        : "=r"(flags)    /* 输出 */
        :                /* 输入无 */
        : "memory"       /* 内存 clobber */
    );
    return flags;
}

/* ---------------------------------------------------------------
 * arch_irq_restore — 恢复保存的 RFLAGS
 *
 * 实现原理：
 *   1. push %0   - 把 flags 压栈
 *   2. popfq     - 弹到 RFLAGS（恢复 IF 位）
 *
 * 如果原 IF=0，恢复后仍关中断；原 IF=1，恢复后开中断。
 *
 * 注意：popfq 不能直接从寄存器到 RFLAGS，
 *       必须通过栈中转（x86 设计）。
 *
 * "memory" clobber：
 *   防止编译器重排
 * --------------------------------------------------------------- */
void arch_irq_restore(u64 flags) {
    __asm__ volatile (
        "pushq %0\n\t"   /* flags 压栈 */
        "popfq\n\t"      /* 弹到 RFLAGS */
        :
        : "r"(flags)     /* 输入 */
        : "memory"       /* 内存 clobber */
    );
}

